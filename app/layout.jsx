import { headers } from "next/headers";
import { displayFont, bodyFont } from "@/lib/fonts";
import ParticleField from "@/components/motion/ParticleField.jsx";
import CursorSpotlight from "@/components/motion/CursorSpotlight.jsx";
import SmoothScroll from "@/components/motion/SmoothScroll.jsx";
import SiteHeader from "@/components/layout/SiteHeader.jsx";
import SiteFooter from "@/components/layout/SiteFooter.jsx";
import "./globals.css";
import { cn } from "@/lib/utils";

export const metadata = {
  title: "ARAH — Post-SPM Pathway Finder",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }) {
  // app/(admin) supplies its own chrome (components/admin/AdminShell.jsx
  // — sidebar, breadcrumb, its own sign-out) via requireAdmin()'s gate,
  // so the public SiteHeader/SiteFooter would duplicate that nav and
  // sign-out control on every admin screen. proxy.js forwards the
  // resolved pathname as the `x-pathname` request header (see proxy.js's
  // comment); reading it here is the only way this Server Component can
  // know the current route, since layouts have no params for their own
  // segment's siblings. `headers()` forcing this subtree dynamic is not
  // a new cost — SiteHeader/SiteFooter already call cookies() via
  // getViewer() on every route today, which already opts the whole app
  // out of static rendering.
  const headersList = await headers();
  const pathname = headersList.get("x-pathname") ?? "";
  const isAdminRoute = pathname === "/admin" || pathname.startsWith("/admin/");

  return (
    <html
      lang="en"
      className={cn("h-full", "antialiased", displayFont.variable, bodyFont.variable, "font-sans")}
    >
      <body className="min-h-full flex flex-col">
        {/* Motion backdrop layers: ParticleField at z-0, CursorSpotlight at
            z-1. Both are siblings behind the content, never inside it, so
            they never participate in document flow or layout. */}
        <ParticleField />
        <CursorSpotlight />
        {/* Content gets its own stacking context above both layers. */}
        <SmoothScroll>
          {/* Global chrome (Task 7): header and footer wrap every page
              except /admin, which supplies its own. Both read the session
              server-side through the shared, cached getViewer() — one
              auth check per request between them. */}
          <div className="relative z-[2] flex min-h-full flex-1 flex-col">
            {isAdminRoute ? null : <SiteHeader />}
            {children}
            {isAdminRoute ? null : <SiteFooter />}
          </div>
        </SmoothScroll>
      </body>
    </html>
  );
}
